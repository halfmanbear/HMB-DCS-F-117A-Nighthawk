"""Generate mod-owned native DCS stroke font resources (no F-16 assets)."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
glyphs=json.loads((ROOT/'tools/data/display_stroke_glyphs.json').read_text())
ns='http://www.w3.org/2000/svg'
ET.register_namespace('',ns)
svg=ET.Element('{'+ns+'}svg',{'width':'320','height':'224','viewBox':'0 0 320 224','version':'1.1'})
chars=[]
for i,code in enumerate(range(33,127)):
    ch=chr(code)
    shape=glyphs.get(ch,glyphs.get(ch.upper(),glyphs['?']))
    group=ET.SubElement(svg,'{'+ns+'}g',{'id':f'g_{code}','transform':f'translate({(i%16)*20} {(i//16)*32})','fill':'none','stroke':'#ffffff','stroke-width':'1','stroke-linecap':'round','stroke-linejoin':'round'})
    for j,points in enumerate(shape.split(';')):
        ET.SubElement(group,'{'+ns+'}polyline',{'id':f'g_{code}_p{j}','points':points,'style':'fill:none;stroke:#ffffff;stroke-width:1;stroke-linecap:round;stroke-linejoin:round'})
    chars.append(f'        {{{code},"g_{code}"}},')
folder=ROOT/'Cockpit/Scripts/Resources/Stroke'
folder.mkdir(parents=True,exist_ok=True)
ET.ElementTree(svg).write(folder/'F117_stroke_font.svg',encoding='utf-8',xml_declaration=True)
(ROOT/'Cockpit/Scripts/display_font.lua').write_text(
    '-- Generated by tools/generate_stroke_font.py. Native vector font.\n'
    'return {\n    class="ceSLineFont", symb_storage="F117_stroke_font",\n'
    '    thickness=0.8, fuzziness=0.5, draw_as_wire=false,\n'
    '    default={13,20},\n    chars={\n'+'\n'.join(chars)+'\n    },\n}\n')
print('Generated native SVG stroke font: 94 visible ASCII glyphs, space uses default advance.')
