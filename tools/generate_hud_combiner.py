"""Export measured HUD glass into DCS indicator-local physical coordinates."""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Read from the live cockpit Blender via MCP on 2026-10-29. These are connector
# locations, not the object transform axes (the triple defines the indicator).
CENTER = (.6580081582069397,-.0015231152065098286,-.0702185109257698)
DOWN = (.6579303741455078,-.0014521254925057292,-.11471275240182877)
RIGHT = (.6580600738525391,-.08740217983722687,-.07024221122264862)

def dot(a,b): return sum(x*y for x,y in zip(a,b))
def sub(a,b): return tuple(x-y for x,y in zip(a,b))
def unit(v): return tuple(x/math.sqrt(dot(v,v)) for x in v)
def cross(a,b): return (a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0])

def generate():
    right=unit(sub(RIGHT,CENTER))
    up=sub(CENTER,DOWN)
    up=unit(tuple(x-dot(up,right)*y for x,y in zip(up,right)))
    normal=unit(cross(right,up))
    surfaces=json.loads((ROOT/'tools/data/cockpit_display_geometry.json').read_text())['surfaces']
    lines=['-- Generated by tools/generate_hud_combiner.py from measured Blender panes.',
           '-- Position: connector-local right, up, normal (normal points toward pilot).',
           '-- Metres; no angular origin or scale gains are included here.', 'return {']
    for name in ['HUD glass 1','HUD glass 2']:
        p=surfaces[name]
        delta=sub(p['center_world_m'],CENTER)
        pos=tuple(dot(delta,axis) for axis in [right,up,normal])
        tilt=-math.degrees(math.atan2(dot(p['up_axis_world'],normal),dot(p['up_axis_world'],up)))
        lines += ['    { -- '+name, '        pos_m={%.12f,%.12f,%.12f},'%pos,
                  f'        tilt_deg={tilt:.9f},',
                  f'        width_m={p["width_m"]:.12f}, height_m={p["height_m"]:.12f},',
                  '        outline_m={']
        lines += ['            {%.12f,%.12f},'%tuple(v) for v in p['boundary_local_m']]
        lines += ['        },','    },']
    path=ROOT/'Cockpit/Scripts/HUD/Indicator/combiner_geometry.lua'
    path.write_text('\n'.join(lines+['}','']),encoding='utf-8')
    print(path)

if __name__=='__main__': generate()
