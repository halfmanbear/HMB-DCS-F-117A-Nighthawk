"""Build the retired bitmap fallback atlas (operational pages now use strokes).
Run from any directory. Requires Pillow. No dependency on another aircraft.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'Cockpit/Scripts/Resources/FONTS'
DEST.mkdir(parents=True, exist_ok=True)
# Fixed square grid, with a narrower 80px character rectangle in each cell.
# This is the same size/resolution/default/chars contract as HUD_def.lua.
CELL, COLS, ROWS = 128, 16, 8
WIDTH, HEIGHT = 80, 128
font = ImageFont.truetype('consolab.ttf', 104)
atlas = Image.new('RGBA', (CELL*COLS, CELL*ROWS), (255,255,255,0))
draw = ImageDraw.Draw(atlas)
for i, code in enumerate(range(32,127)):
    glyph=chr(code)
    bounds=font.getbbox(glyph)
    x=(i%COLS)*CELL + (WIDTH-(bounds[2]-bounds[0]))//2-bounds[0]
    y=(i//COLS)*CELL + (HEIGHT-(bounds[3]-bounds[1]))//2-bounds[1]
    draw.text((x,y), glyph, font=font, fill=(255,255,255,255))
atlas.save(DEST/'F117_Display_Bold.dds')  # Uncompressed RGBA DDS, explicit alpha.
# PNG is a review artifact; DCS consumes the DDS.
preview=ROOT/'tmp/display-font-atlas.png'
preview.parent.mkdir(exist_ok=True)
Image.alpha_composite(Image.new('RGBA',atlas.size,(10,10,10,255)),atlas).save(preview)
chars=''.join(f'        {{{code},{WIDTH},{HEIGHT}}},\n' for code in range(32,127))
(ROOT/'Cockpit/Scripts/display_bitmap_font.lua').write_text(
    '-- Generated by tools/generate_display_font.py; fixed grid RGBA atlas.\n'
    'return {\n'
    '    texture=LockOn_Options.script_path.."Resources/FONTS/F117_Display_Bold",\n'
    f'    size={{{COLS},{ROWS}}}, resolution={{{CELL*COLS},{CELL*ROWS}}},\n'
    f'    default={{{WIDTH},{HEIGHT}}},\n'
    '    chars={\n'+chars+'    },\n}\n')
print(f'Generated {COLS*CELL} x {ROWS*CELL} font atlas, 95 ASCII glyphs')
